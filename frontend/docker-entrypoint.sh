# Runtime env injection for the UI. Writes /env.js (served by nginx, loaded by
# index.html + console.html before the bundle) from the ENVIRONMENT and BRANDING
# pod env vars so the SAME image renders as:
#   - the default open-source KVM Orchestrator build, or your own white-labelled
#     build (BRANDING), and
#   - live (blue) or test (red + warning banner) (ENVIRONMENT),
# purely by namespace config — no separate image, no rebuild to rebrand/retheme.
set -e

ENVIRONMENT="${ENVIRONMENT:-live}"
BRANDING="${BRANDING:-kvm-orchestrator}"
ENV_JS="/usr/share/nginx/html/env.js"

cat > "$ENV_JS" <<EOF
window.__ENV__ = { ENVIRONMENT: "${ENVIRONMENT}", BRANDING: "${BRANDING}" };
EOF

# Trusted reverse proxies for nginx real_ip (comma-separated CIDRs/IPs).
# Default = k3s/RKE2 default pod CIDR + loopback; set to your cluster's pod CIDR.
TRUSTED_PROXIES="${TRUSTED_PROXIES:-10.42.0.0/16,127.0.0.1}"
REAL_IP_CONF="/etc/nginx/conf.d/00-real-ip.conf"
{
  echo "# generated by docker-entrypoint.sh from TRUSTED_PROXIES"
  echo "${TRUSTED_PROXIES}" | tr ',' '\n' | while read -r cidr; do
    cidr="$(echo "$cidr" | tr -d '[:space:]')"
    case "$cidr" in
      "") ;;
      *[!0-9A-Fa-f.:/]*) echo "wvc-ui: ignoring invalid TRUSTED_PROXIES entry '$cidr'" >&2 ;;
      *) echo "set_real_ip_from ${cidr};" ;;
    esac
  done
} > "${REAL_IP_CONF}.tmp" && mv "${REAL_IP_CONF}.tmp" "${REAL_IP_CONF}" \
  || echo "wvc-ui: could not write ${REAL_IP_CONF}; using the image default" >&2

echo "wvc-ui: wrote ${ENV_JS} (ENVIRONMENT=${ENVIRONMENT} BRANDING=${BRANDING})"

exec nginx -g 'daemon off;'
